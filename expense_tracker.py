import json

FILENAME = "expenses.json"


def load_data():
    try:
        with open(FILENAME) as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        return []


def save_data():
    with open(FILENAME, "w") as f:
        json.dump(expenses, f)


expenses = load_data()


def add_expense():
    title = input("What did you spend on? ").strip().title()
    category = input("Category (Food, Travel, Study, Other): ").strip().title()
    try:
        amount = float(input("Amount in Rs: "))
    except ValueError:
        print("Amount must be a number")
        return
    if amount <= 0:
        print("Amount must be above 0")
        return
    expenses.append({"title": title, "category": category, "amount": amount})
    save_data()
    print("Expense added")


def view_expenses():
    if len(expenses) == 0:
        print("No expenses yet")
        return
    total = 0
    for i, e in enumerate(expenses, 1):
        print(f"{i}. {e['title']} ({e['category']}): Rs. {e['amount']:.2f}")
        total = total + e["amount"]
    print(f"Total: Rs. {total:.2f}")


def category_totals():
    if len(expenses) == 0:
        print("No expenses yet")
        return
    totals = {}
    for e in expenses:
        cat = e["category"]
        if cat in totals:
            totals[cat] = totals[cat] + e["amount"]
        else:
            totals[cat] = e["amount"]
    for cat, amount in totals.items():
        print(f"{cat}: Rs. {amount:.2f}")


def delete_expense():
    if len(expenses) == 0:
        print("No expenses yet")
        return
    view_expenses()
    try:
        number = int(input("Number to delete: "))
    except ValueError:
        print("Please enter a number")
        return
    if number < 1 or number > len(expenses):
        print("No expense with that number")
        return
    removed = expenses.pop(number - 1)
    save_data()
    print(f"Deleted: {removed['title']}")


def main():
    while True:
        print()
        print("1. Add expense")
        print("2. View expenses")
        print("3. Category totals")
        print("4. Delete expense")
        print("5. Quit")
        choice = input("Choose: ").strip()

        if choice == "1":
            add_expense()
        elif choice == "2":
            view_expenses()
        elif choice == "3":
            category_totals()
        elif choice == "4":
            delete_expense()
        elif choice == "5":
            break
        else:
            print("Invalid choice")

    print("Goodbye")


main()

